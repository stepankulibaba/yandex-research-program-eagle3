# baseline = the authors' trainer and layers; ours = NeMo AutoModel's EAGLE-3 recipe with our layers and fc_norm.
# Layer index i = input of decoder layer i = HF hidden_states[i] (the authors' convention).
# SGLang / NeMo count "output of layer i" instead, i.e. our index minus one (see export.py).
N_LAYERS = 32                 # LLaMA-3.1-8B
VARIANTS = {
    # EAGLE-3 as published: layers 2, N/2, N-3, no normalisation; train.py (the authors' code)
    'baseline': {'layers': [2, N_LAYERS // 2, N_LAYERS - 3], 'fc_norm': False, 'trainer': 'authors'},
    # our method: N/2, 0.7N, N-3, each state RMS-normalised with its own learned scale before fc
    # (EAGLE-3.1 `fc_norm` in NeMo / vLLM); trained with the authors' code like baseline (since 2026-10-13 00:15):
    # NeMo's trainer (train_nemo_full.py) diverged at every lr from 2e-4 down to 2e-5 around step 600-930
    # (attention logit growth), see reports/incidents/README.md. 'nemo' here would run train_nemo_full.py again.
    'ours': {'layers': [N_LAYERS // 2, round(0.7 * N_LAYERS), N_LAYERS - 3], 'fc_norm': True, 'trainer': 'authors'},
}

# NeMo AutoModel (pinned commit 3770b1e1, the clone and venv of the speed study) and its EAGLE-3 recipe for
# LLaMA-3.1-8B on PerfectBlend (examples/speculative/eagle3/llama_eagle3_perfectblend.yaml), kept as is:
# 8 GPUs x micro-batch 1 x accumulation 4 = 32 packed rows of 2048 tokens per step -> here 1 GPU x 1 x 32.
NEMO_DIR = _path('BT_NEMO_DIR', ROOT / 'nemo_speed' / 'Automodel')
NEMO_PYTHON = NEMO_DIR / '.venv' / 'bin' / 'python'
# One change: peak lr 1e-4 instead of 2e-4. With fp32 master weights (see train_nemo_full.py) the recipe's 2e-4
# diverged at lr ~1.3e-4 during warmup (loss 3.2 -> 9.5, 2026-10-12); in its pure-bf16 form most small updates are
# rounded away, which damps the step.
NEMO_RECIPE = {'lr': 1e-4, 'betas': [0.9, 0.95], 'weight_decay': 0.0, 'warmup_ratio': 0.05, 'min_lr_ratio': 0.1,
               'max_grad_norm': 1.0, 'ttt_steps': 4, 'packed_sequence_size': 2048, 'micro_batch_size': 1,
               'grad_accumulation_steps': 32, 'draft_vocab_size': 32000, 'freeze_embeddings': True}
NEMO_CHECKPOINT_MINUTES = 20  # ours: frequent checkpoints, so a rollback after a divergence loses little
NEMO_KEEP_CHECKPOINTS = 4
# skip_grad_norm: an optimizer step whose gradient norm (before clipping) is non-finite or above it is skipped,
# as DeepSpeed fp16 skips overflow steps for baseline (the norm is ~1-1.5 in healthy training);
# loss_jump / grad_norm: a divergence -> rollback to the last healthy checkpoint with half the lr.
# from_step: the loss check starts there (the loss of an untrained draft wanders by more than 1).
# (2026-10-12 23:20) skipping steps with a finite but large norm froze the model in a bad state (attention logit
# growth: the same weights for 120 steps): now only inf/NaN is skipped, and a norm > 10 means a rollback.
NEMO_GUARD = {'skip_grad_norm': float('inf'), 'from_step': 100, 'loss_jump': 1.0, 'grad_norm': 10.0, 'margin_steps': 50, 'lr_factor': 0.5,
              'max_rollbacks': 3}
NEMO_COMPILE = True           # the speed-up measured in the speed study (draft torch.compile; FP8 gave ~1 % more)

