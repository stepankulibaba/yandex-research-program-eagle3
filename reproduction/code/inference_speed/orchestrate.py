    def author_benchmarks(self):
        """EAGLE-3 and plain generation with SafeAILab/EAGLE's own scripts, T=0 then T=1 (results/<mode>/eagle)."""
        wanted = os.environ.get('AUTHOR_TEMPERATURES', '0,1').split(',')
        for temperature, prefix in ((0, ''), (1, 't1_')):
            if str(temperature) not in wanted:
                continue
            for bench in BENCHES:
                expected = questions(HERE / 'EAGLE', bench, self.questions_per_bench)
                for use_eagle, script in ((True, 'gen_ea_answer_llama3chat'),
                                          (False, 'gen_baseline_answer_llama3chat')):
                    name = ('ea_' if use_eagle else 'base_') + prefix + bench
                    path = self.results / 'eagle' / (name + '.jsonl')
                    path.parent.mkdir(parents=True, exist_ok=True)
                    cmd = [self.py_eagle, '-m', 'eagle.evaluation.' + script, '--temperature', str(temperature),
                           '--ea-model-path', self.draft, '--base-model-path', self.model,
                           '--bench-name', bench, '--question-begin', '0',
                           '--question-end', str(self.questions_per_bench),
                           '--total-token', str(AUTHOR_TREE['total_token']), '--depth', str(AUTHOR_TREE['depth']),
                           '--top-k', str(AUTHOR_TREE['top_k']),
                           '--answer-file', path]
                    if use_eagle:
                        cmd += ['--use_eagle3']
                    settings = {'protocol': 'unchanged-author', 'temperature': temperature,
                                'tree': [AUTHOR_TREE['total_token'], AUTHOR_TREE['depth'], AUTHOR_TREE['top_k']]}
                    self.attempt(name, self.produce, name, path, settings,
                                 lambda p, e=expected: validate_answers(p, e, 'eagle'), cmd, cwd=HERE / 'EAGLE',
                                 timeout=int(os.environ.get('BENCH_TIMEOUT', '5400')))
                self.attempt('inference_summary', self.inference_summary)

    def inference_summary(self):
        self.command('inference_summary', [self.py_eagle, HERE / 'summarize.py', self.model, self.results],
                     timeout=120)

    # ================================================================================================================
    # 3b. SGLang
    # ================================================================================================================
    @contextlib.contextmanager
    def sglang_server(self, name, tree=None):
        """Start an SGLang server (plain, or EAGLE-3 with `tree` = (steps, topk, tokens)); yield its URL."""
        port = int(os.environ.get('SGLANG_PORT', '30000'))
        self.wait_for_free_port(port)
        if not all(shutil.which(x, path=self.env['PATH']) for x in ('gcc', 'g++', 'ninja')):
            raise RuntimeError('Missing gcc/g++/ninja for runtime kernels; run setup before the allocation')
        if tree:     # without the tree-sampling kernel SGLang silently verifies T=1 greedily
            self.command('tree_sampling_kernel', [self.py_sglang, '-c',
                'from sglang.srt.speculative.spec_utils import TREE_SPEC_KERNEL_AVAILABLE; '
                'assert TREE_SPEC_KERNEL_AVAILABLE, "T=1 would fall back to greedy"'],
                env=self.sglang_process_env(), timeout=300)
        # Triton attention and PyTorch sampling: kernels that need no CUDA toolkit (flashinfer may JIT-compile).
        cmd = [self.py_sglang, '-m', 'sglang.launch_server', '--model-path', self.model, '--dtype', 'float16',
               '--host', '127.0.0.1', '--port', str(port), '--mem-fraction-static', '0.8',
               '--attention-backend', 'triton', '--sampling-backend', 'pytorch', '--disable-radix-cache',
               '--random-seed', '0']     # tree verification at T=1 uses the server's global RNG
        if tree:
            steps, topk, tokens = tree
            cmd += ['--speculative-algorithm', 'EAGLE3', '--speculative-draft-model-path', self.draft,
                    '--speculative-num-steps', str(steps), '--speculative-eagle-topk', str(topk),
                    '--speculative-num-draft-tokens', str(tokens)]
        log = self.logs / ('server_' + name + '.log')
        url = f'http://127.0.0.1:{port}'
        proc = None
        with log.open('w', encoding='utf-8') as stream:
            try:
                proc = subprocess.Popen([str(x) for x in cmd], cwd=HERE, env=self.sglang_process_env(), stdout=stream,
                                        stderr=subprocess.STDOUT, start_new_session=True)
                self.wait_until_ready(proc, url, log, tree)
                self.active_server_log = log
                yield url
                if 'Falling back to greedy verification' in log.read_text(encoding='utf-8', errors='replace'):
                    raise RuntimeError('T=1 degraded to greedy verification')
            finally:
                self.active_server_log = None
                terminate_owned(proc)

    def wait_for_free_port(self, port, seconds=180):
        """The previous server may need a moment to release the port; we wait, but never kill its owner."""
        until = time.monotonic() + seconds
        while True:
            with socket.socket() as sock:
                sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)   # ignore TIME_WAIT leftovers
                try:
                    sock.bind(('127.0.0.1', port))
                    return
                except OSError:
                    if time.monotonic() > until:
                        raise RuntimeError(f'Port {port} is still taken after {seconds} s')
            time.sleep(2)

    def wait_until_ready(self, proc, url, log, tree):
        """Poll /server_info until the server answers, and check it runs the model and tree we asked for."""
        name = log.stem.removeprefix('server_')
        until = time.monotonic() + self.remaining(600)
        while time.monotonic() < until:
            if proc.poll() is not None:
                raise RuntimeError(f'Server exited ({proc.returncode}): {log.name}')
            try:
                info = http_json(url + '/server_info')
            except (OSError, json.JSONDecodeError):
                time.sleep(1)
                continue
            server_args = info.get('server_args', info)
            if Path(server_args['model_path']).resolve() != self.model.resolve():
                raise RuntimeError('Wrong server target model')
            if tree:
                keys = ('speculative_num_steps', 'speculative_eagle_topk', 'speculative_num_draft_tokens')
                if any(server_args.get(k) != v for k, v in zip(keys, tree)):
                    raise RuntimeError('Wrong speculative server configuration')
            elif server_args.get('speculative_algorithm') not in (None, 'NONE'):
                raise RuntimeError('Expected a plain server')
            atomic_json(self.logs / ('server_' + name + '.json'), info)
            return
        # Not TimeoutError: that one means "the night is over" and would stop every remaining stage.
        raise RuntimeError('Server did not start in time')

    def sglang_benchmarks(self):
        """For each server config: start the server once, run every unfinished benchmark against it."""
        configs = [('base', None)] + [(name, (steps, topk, tokens)) for name, steps, topk, tokens in SGLANG_TREES]
        for name, tree in configs:
            temperatures = (0, 1) if name in SGLANG_T1_CONFIGS else (0,)
            jobs = []
            for temperature in temperatures:
                seeds = (0, 1, 2) if temperature and not self.smoke else (0,)
                for seed in seeds:
                    prefix = name + ('_t1' if temperature else '') + (f'_seed{seed}' if seed else '')
                    for bench in BENCHES:
                        path = self.results / 'sglang' / f'{prefix}_{bench}.json'
                        expected = questions(HERE / 'EAGLE', bench, self.questions_per_bench)
                        settings = {'protocol': 'bounded-http-no-prefix-cache-v2', 'tree': tree,
                                    'temperature': temperature, 'seed': seed}
                        manifest = {**self.base_manifest, 'stage': prefix + '_' + bench, **settings}
                        validator = lambda p, e=expected: validate_answers(p, e, 'sglang')
                        if finished(path, manifest, validator):
                            self.status(prefix + '_' + bench, 'REUSED')
                        else:
                            jobs.append((prefix, bench, temperature, seed, path, settings, validator))
            if jobs:
                self.attempt('server_' + name, self.run_sglang_jobs, name, tree, jobs)

    def run_sglang_jobs(self, name, tree, jobs):
        with self.sglang_server(name, tree) as url:
            for prefix, bench, temperature, seed, path, settings, validator in jobs:
                env = {**self.env, 'SPECULATIVE': '1' if tree else '0', 'SAMPLING_SEED': str(seed)}
                stage = prefix + '_' + bench
                self.attempt(stage, self.produce, stage, path, settings, validator,
                             [self.py_sglang, HERE / 'sglang_client.py', url, self.model, bench, path,
                              str(temperature)],
                             env=env, timeout=int(os.environ.get('BENCH_TIMEOUT', '5400')))
                self.attempt('inference_summary', self.inference_summary)

