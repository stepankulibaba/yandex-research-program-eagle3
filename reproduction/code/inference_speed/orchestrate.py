    def checkout(self, folder, url, commit, name):
        """Clone `url` into `folder` (once) and check out `commit`; refuse if someone edited tracked files."""
        if not (folder / '.git').is_dir():
            if folder.exists():
                raise RuntimeError(f'{folder.name} exists without .git; refusing deletion')
            self.command(name + '_clone', ['git', 'clone', url, folder], timeout=900)
        git = ['git', '-C', str(folder)]
        current = subprocess.check_output(git + ['rev-parse', 'HEAD'], text=True).strip()
        edited = subprocess.check_output(git + ['status', '--porcelain', '--untracked-files=no'], text=True).strip()
        if edited:
            raise RuntimeError(f'{folder.name} has changes; refusing automatic checkout')
        if current != commit:
            self.command(name + '_fetch', ['git', '-C', folder, 'fetch', 'origin', commit], timeout=600)
            self.command(name + '_checkout', ['git', '-C', folder, 'checkout', '--detach', commit], timeout=60)
        if subprocess.check_output(git + ['rev-parse', 'HEAD'], text=True).strip() != commit:
            raise RuntimeError('Repository pin mismatch')

    def virtualenv(self, python, name, requirements, import_check):
        """Create/update a virtualenv; pip runs only when the requirement list changed. Then test the imports."""
        wanted = digest({'schema': SCHEMA, 'requirements': requirements, 'imports': import_check})
        marker = python.parent.parent / '.installed.json'
        if not python.exists():
            try:
                self.command(name + '_venv', [sys.executable, '-m', 'venv', python.parent.parent], timeout=120)
            except subprocess.CalledProcessError:
                # Some images (e.g. DataSphere) ship Python without ensurepip; `virtualenv` brings its own pip.
                shutil.rmtree(python.parent.parent, ignore_errors=True)
                self.command(name + '_virtualenv_install', [sys.executable, '-m', 'pip', 'install', '-q', 'virtualenv'],
                             timeout=600)
                self.command(name + '_virtualenv', [sys.executable, '-m', 'virtualenv', python.parent.parent],
                             timeout=300)
        try:
            up_to_date = read_json(marker)['desired'] == wanted
        except (OSError, ValueError, KeyError):
            up_to_date = False
        if not up_to_date:
            self.command(name + '_pip', [python, '-m', 'pip', 'install', *requirements], timeout=3600)
        self.command(name + '_imports', [python, '-c', import_check], timeout=120)
        freeze = subprocess.check_output([str(python), '-m', 'pip', 'freeze'], text=True, timeout=60)
        state = {'desired': wanted, 'freeze_sha256': digest(sorted(freeze.splitlines()))}
        atomic_json(marker, state)
        self.environment[name] = state

