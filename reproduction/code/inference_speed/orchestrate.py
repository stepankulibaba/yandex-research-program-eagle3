"""The whole GPU run: environments, then every measurement stage, restartable and with a deadline.

    python3 orchestrate.py night       everything (night.sh)
    python3 orchestrate.py check       the same on 2 questions / 40 examples: a quick smoke test (check.sh)
    python3 orchestrate.py setup       only environments and models
    python3 orchestrate.py inference   only 3a, 3b and the regeneration probe (run.sh)
    python3 orchestrate.py train       only the training speed (../nemo_speed/run.sh)
    python3 orchestrate.py author      only the authors' code on this GPU: profile, then 3a (author.sh; e.g. an A100)

Order of the night (most important first):
    1. 3a  the authors' evaluation scripts, unchanged: EAGLE-3 and plain generation, T=0 and T=1
    2. 4   training step speed: the authors' trainer vs NeMo, same data
    3. 5   regeneration probe (how fast the target rewrites the training answers) and the GPU-hour budget
    4. 3b  SGLang: plain server and EAGLE-3 trees, T=0 (and T=1 with three seeds for the paper tree)
    5. 4   NeMo speed-ups: packing, flash-attn 2, torch.compile, FP8, micro-batch 4

Rules:
    - Each result gets a "done" marker (common.finish); a restart skips finished results.
    - A failed stage is recorded as FAILED and the night continues; only NIGHT_SECONDS (default 7 h) or a
      signal stops it. stages.json lists the status of every stage, logs/<mode>/<stage>.log its output.
    - check mode writes to results/smoke, logs/smoke, ../nemo_speed/artifacts/smoke; the night to .../main.
"""
